"""Inspect source mappings or generate kernel-checked Lean VC modules."""

import argparse
import json
from pathlib import Path
import subprocess
import sys
import tempfile

from .emit import emit, vc_sources
from .source import FrontendError, extract


ROOT = Path(__file__).resolve().parents[1]
MARKER = "VERIPY_SOURCE_MAP "
GENERATED = "-- Generated by python3 -m veripy_frontend."


def run_lean(text):
    build = subprocess.run(["lake", "build", "VeriPyAsm.Frontend.Checkpoint",
                            "VeriPyAsm.Verification.VC.Generate", "VeriPyAsm.Verification.VC.Source"], cwd=ROOT,
                           text=True, capture_output=True, timeout=180)
    if build.returncode:
        raise FrontendError("Lean dependencies failed to build:\n" + build.stdout + build.stderr)
    with tempfile.TemporaryDirectory(prefix="veripy-source-") as temporary:
        path = Path(temporary) / "Generated.lean"
        path.write_text(text)
        result = subprocess.run(["lake", "env", "lean", str(path)], cwd=ROOT,
                                text=True, capture_output=True, timeout=180)
    if result.returncode:
        raise FrontendError("Lean rejected the generated module:\n" + result.stdout + result.stderr)
    reports = [json.loads(line.split(MARKER, 1)[1]) for line in result.stdout.splitlines() if MARKER in line]
    if len(reports) != 1:
        raise FrontendError("Lean did not return exactly one checked source mapping")
    return reports[0]


def write_generated(path, text, bundle):
    companion = path.with_suffix(".source.json")
    if path.exists() and not path.read_text().startswith(GENERATED):
        raise FrontendError(f"refusing to overwrite a user-owned file: {path}")
    if companion.exists():
        try:
            previous = json.loads(companion.read_text())
        except (ValueError, UnicodeError):
            previous = {}
        if not isinstance(previous, dict) or previous.get("generator") != "veripy_frontend":
            raise FrontendError(f"refusing to overwrite a user-owned file: {companion}")
    path.parent.mkdir(parents=True, exist_ok=True)
    # Validate before publishing; stage both outputs on the destination filesystem.
    with tempfile.TemporaryDirectory(prefix=".veripy-source-", dir=path.parent) as temporary:
        staged = Path(temporary)
        (staged / "Module.lean").write_text(text)
        (staged / "Source.json").write_text(json.dumps(bundle, ensure_ascii=False, indent=2) + "\n")
        (staged / "Source.json").replace(companion)
        (staged / "Module.lean").replace(path)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    for command in ("inspect", "generate"):
        sub = commands.add_parser(command)
        sub.add_argument("source", type=Path)
        sub.add_argument("--function", required=True)
        sub.add_argument("--namespace", default="Generated.Source")
        sub.add_argument("--json", action="store_true", help="print the complete companion bundle")
        if command == "generate":
            sub.add_argument("--output", type=Path, required=True, help="destination .lean file")
    args = parser.parse_args(argv)
    try:
        if args.command == "generate" and (args.output.suffix != ".lean" or
                                           args.output.resolve() == args.source.resolve()):
            raise FrontendError("output must be a separate .lean file")
        function = extract(args.source, args.function, inspection=args.command == "inspect")
        text = emit(function, args.namespace, mapping_only=args.command == "inspect")
        mapping = run_lean(text)
        bundle = function.bundle()
        bundle["mapping"] = mapping
        bundle["missingAnnotations"] = list(function.missing)
        bundle["status"] = "mapping_checked" if args.command == "inspect" else "vcs_generated"
        if args.command == "generate":
            loop_mapping = mapping["loopMapping"] if function.checkpoints else mapping
            mappings = loop_mapping["loops"] if function.scoped else [loop_mapping]
            bundle["verificationConditions"] = [dict(item, goal=args.namespace + ".generated.VC." + item["field"])
                for item in vc_sources(function, [mapped["header"] for mapped in mappings])]
            if function.checkpoints:
                for checkpoint in bundle["checkpoints"]["items"]:
                    checkpoint["vcGoal"] = args.namespace + ".generated.VC.checkpoint_" + checkpoint["origin"]["label"]
            write_generated(args.output, text, bundle)
        if args.json:
            print(json.dumps(bundle, ensure_ascii=False, indent=2))
        else:
            loop_mapping = mapping["loopMapping"] if function.checkpoints else mapping
            mappings = loop_mapping["loops"] if function.scoped else [loop_mapping]
            for index, (loop, mapped) in enumerate(zip(function.loops, mappings)):
                parent = function.loops[loop.parent].label if loop.parent is not None else "root"
                print(f"{function.path}:{loop.node.lineno}: {loop.label}: checked loop header at byte {mapped['header']} ({parent})")
                print("  backedges: " + ", ".join(f"{edge['sourcePC']} -> {edge['targetPC']}" for edge in mapped["backedges"]))
            if function.checkpoints:
                for checkpoint, mapped in zip(function.checkpoints, mapping["checkpoints"]):
                    line = checkpoint.node.lineno if checkpoint.kind == "assertion" else checkpoint.directive.line
                    location = ", ".join(f"{e['sourcePC']} -> {e['targetPC']}" for e in mapped["boundaryEdges"])
                    kind = "assertion entry" if checkpoint.kind == "assertion" else "hint boundary"
                    print(f"{function.path}:{line}: {checkpoint.label}: checked {kind} on {location}")
                if args.command == "inspect":
                    print("  Checkpoint mappings are structural; their claims have not been proved.")
            print("  locals: " + ", ".join(f"{name}={i}" for i, name in enumerate(function.code.co_varnames)))
            for missing in function.missing:
                print(f"  missing: # veripy: {missing}")
            if args.command == "generate":
                for condition in bundle["verificationConditions"]:
                    origin = condition["source"]
                    print(f"  obligation: {condition['goal']} ({origin['path']}:{origin['line']})")
                print(f"Generated checked VC declarations: {args.output}")
                print("Contract verification still requires proofs of all generated VCs.")
    except (FrontendError, OSError, subprocess.TimeoutExpired) as error:
        print(f"veripy: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
