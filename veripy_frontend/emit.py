"""Emit literal artifacts and typed Lean predicates from the restricted AST."""

import ast
import json
import re

from .source import FrontendError


def string(value):
    # Lean accepts JSON's common escapes; use explicit hex for other controls.
    return '"' + ''.join({'"': '\\"', '\\': '\\\\', '\n': '\\n', '\r': '\\r', '\t': '\\t'}.get(
        c, f'\\x{ord(c):02x}' if ord(c) < 32 else c) for c in value) + '"'


def seq(values):
    return "[" + ", ".join(values) + "]"


def span(value):
    return "{ " + ", ".join(f"{key} := {value[key]}" for key in ("line", "column", "endLine", "endColumn")) + " }"


def expression(node, current, old, result="r"):
    if isinstance(node, ast.Constant):
        if type(node.value) is bool:
            return "True" if node.value else "False"
        return f"({node.value} : Int)"
    if isinstance(node, ast.Name):
        return result if node.id == "result" else current[node.id]
    if isinstance(node, ast.Call):
        return old[node.args[0].id] if node.func.id == "old" else "True"
    if isinstance(node, ast.BinOp):
        op = {ast.Add: "+", ast.Sub: "-", ast.Mult: "*"}[type(node.op)]
        return f"({expression(node.left, current, old, result)} {op} {expression(node.right, current, old, result)})"
    if isinstance(node, ast.UnaryOp):
        op = {ast.USub: "-", ast.UAdd: "+", ast.Not: "¬"}[type(node.op)]
        value = expression(node.operand, current, old, result)
        return value if op == "+" else f"({op}{value})"
    if isinstance(node, ast.BoolOp):
        op = " ∧ " if isinstance(node.op, ast.And) else " ∨ "
        return "(" + op.join(expression(v, current, old, result) for v in node.values) + ")"
    if isinstance(node, ast.Compare):
        operands = [node.left, *node.comparators]
        ops = {ast.Lt: "<", ast.LtE: "≤", ast.Eq: "=", ast.NotEq: "≠", ast.Gt: ">", ast.GtE: "≥"}
        return "(" + " ∧ ".join(f"({expression(a, current, old, result)} {ops[type(op)]} {expression(b, current, old, result)})"
                                   for a, op, b in zip(operands, node.ops, operands[1:])) + ")"
    raise FrontendError(f"internal unsupported annotation: {type(node).__name__}")


def annotation_reads(node):
    """Current-state names; old(parameter) reads the function-entry ghost."""
    if isinstance(node, ast.Call) and node.func.id == "old":
        return set()
    if isinstance(node, ast.Name):
        return {node.id}
    return set().union(*(annotation_reads(child) for child in ast.iter_child_nodes(node)))


def emit(function, namespace, *, mapping_only=False):
    if function.checkpoints and not mapping_only:
        raise FrontendError("source checkpoints support inspect only; checkpoint VC generation is not implemented yet")
    if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*(?:\.[A-Za-z_][A-Za-z_0-9]*)*", namespace):
        raise FrontendError("namespace must be a dotted Lean identifier")
    bundle = function.bundle()
    a, source = bundle["artifact"], bundle["source"]
    values = []
    for constant in a["constants"]:
        values.append({"none": ".none", "bool": ".bool " + str(constant.get("value", False)).lower(),
                       "int": f".int ({constant.get('value', 0)})"}[constant["tag"]])
    fields = [f"build := {string(a['build'])}", f"name := {string(a['name'])}",
              f"code := {seq(map(str, a['code']))}", f"constants := {seq(values)}"]
    for key in ("argCount", "posOnlyArgCount", "kwOnlyArgCount", "stackSize", "flags"):
        fields.append(f"{key} := {a[key]}")
    for key in ("localNames", "names", "freeVars", "cellVars"):
        fields.append(f"{key} := {seq(map(string, a[key]))}")
    fields.append(f"exceptionTable := {seq(map(str, a['exceptionTable']))}")
    positions = seq("none" if p is None else f"some ({span(p)})" for p in source["positions"])
    loop = source["loop"]
    text = f'''-- Generated by python3 -m veripy_frontend. Edit the source annotations, not this file.
import VeriPyAsm.Frontend.Mapping
import VeriPyAsm.Verification.VC.Generate

set_option maxRecDepth 8000
set_option maxHeartbeats 8000000
set_option linter.unusedVariables false

namespace {namespace}
open VeriPyAsm VeriPyAsm.Semantics VeriPyAsm.Verification

def artifact : CPython.V314.Artifact where
  ''' + "\n  ".join(fields) + f'''

def admitted : Admitted artifact := admit_bytecode% artifact

def source : Frontend.Source where
  path := {string(source['path'])}
  digest := {string(source['digest'])}
  functionName := {string(source['functionName'])}
  localNames := {seq(map(string, source['localNames']))}
  positions := {positions}
  loop := {{
    label := {string(loop['label'])}
    statement := {span(loop['statement'])}
    test := {span(loop['test'])}
    body := {span(loop['body'])} }}

veripy_source sourceMap from admitted for source

#eval IO.println ("VERIPY_SOURCE_MAP " ++ (Lean.toJson sourceMap).compress)
'''
    if function.scoped:
        declarations = []
        for i, origin in enumerate(bundle["sources"]):
            loop = origin["loop"]
            declarations.append(f"""def source{i} : Frontend.Source := {{ source with loop := {{
    label := {string(loop['label'])}
    statement := {span(loop['statement'])}
    test := {span(loop['test'])}
    body := {span(loop['body'])} }} }}""")
        mapping = "\n\n".join(declarations) + f"""

def sources : List Frontend.Source := {seq(f'source{i}' for i in range(len(function.loops)))}
veripy_sources sourceMaps from admitted for sources

#eval IO.println ("VERIPY_SOURCE_MAP " ++ (Lean.toJson sourceMaps).compress)
"""
        text = text[:text.index("veripy_source sourceMap from admitted for source")] + mapping
    if function.checkpoints:
        text = text.replace("import VeriPyAsm.Frontend.Mapping", "import VeriPyAsm.Frontend.Checkpoint")
        origins = ["{ label := " + string(c.label) + f", kind := .{c.kind}, statement := " +
                   span(c.bundle()["origin"]["statement"]) + " }"
                   for c in function.checkpoints]
        text += f'''
def checkpointOrigins : List Frontend.CheckpointOrigin := {seq(origins)}
veripy_checkpoints checkpointMaps from admitted for source at checkpointOrigins
'''
        # Keep the old loop-only report shape stable. The extended inspection
        # report contains the exact same loop map and separate checkpoint edges.
        mapping_name = "sourceMaps" if function.scoped else "sourceMap"
        old_report = f'#eval IO.println ("VERIPY_SOURCE_MAP " ++ (Lean.toJson {mapping_name}).compress)'
        text = text.replace(old_report, "")
        text += f'''
#eval IO.println ("VERIPY_SOURCE_MAP " ++ (Lean.Json.mkObj [
  ("loopMapping", Lean.toJson {mapping_name}),
  ("checkpoints", Lean.toJson checkpointMaps)]).compress)
'''
    if mapping_only:
        return text + f"\nend {namespace}\n"
    parameters = function.parameters
    if len(parameters) == 0:
        ghost, old = "Unit", {}
    elif len(parameters) == 1:
        ghost, old = "Int", {parameters[0]: "old"}
    else:
        ghost = " × ".join("Int" for _ in parameters)
        old = {name: "old" + ".2" * i + (".1" if i < len(parameters) - 1 else "")
               for i, name in enumerate(parameters)}
    locals_ = list(function.code.co_varnames)
    current = {name: f"v{i}" for i, name in enumerate(locals_)}
    prelocals = seq(f"some (.int {old[name]})" if name in old else "none" for name in locals_)
    currentlocals = seq(f"some (.int {current[name]})" for name in locals_)
    reads = [name for name in locals_ if name in annotation_reads(function.ensures)]
    final = {name: f"f{i}" for i, name in enumerate(reads)}
    postfacts = ["value = .int r"] + [f"final.locals[{locals_.index(name)}]? = some (some (.int {final[name]}))" for name in reads]
    postfacts.append(expression(function.ensures, final, old))
    rank = expression(function.decreases, current, old) if function.decreases else None
    invariant = expression(function.invariant, current, old)
    if rank is not None:
        invariant += f" ∧ 0 ≤ {rank}"
    contract = f'''
def contract : Contract ({ghost}) where
  pre old initial := {expression(function.requires, old, old)} ∧
    initial = {{ locals := {prelocals} }}
  post old _ value final := ∃ {' '.join(['r', *final.values()])} : Int,
    {' ∧ '.join(postfacts)}
  raises _ _ _ _ := False
'''
    text += contract
    if function.scoped:
        return text + scoped_specification(function, ghost, old, current) + f"\nend {namespace}\n"
    text += f'''
def invariant (old : {ghost}) (current : Frame) : Prop :=
  ∃ {' '.join(current.values())} : Int,
    current = {{ pc := sourceMap.header, locals := {currentlocals} }} ∧
    {invariant}
'''
    if rank is not None:
        text += f'''
def rank (old : {ghost}) (current : Frame) : Nat :=
  match current.locals with
  | {currentlocals} => ({rank}).toNat
  | _ => 0
'''
    text += f'''
def specification : VC.Specification ({ghost}) where
  contract := contract
  mode := .{'totalCorrectness' if function.mode == 'total' else 'partialCorrectness'}
  cutpoints := [sourceMap.header]
  invariant old _ := invariant old
'''
    if rank is not None:
        text += "  ranking := some (fun old _ => rank old)\n"
    rules = "contract, invariant, sourceMap" + (", rank" if rank is not None else "")
    text += f'''
veripy_generate generated from admitted for specification unfolding [{rules}]

end {namespace}
'''
    return text


def scoped_specification(function, ghost, old, current):
    """Per-loop snapshots frame unchanged slots; every framing fact is a VC."""
    text, rules = "", ["contract", "sourceMaps"]
    locals_ = list(function.code.co_varnames)
    for index, loop in enumerate(function.loops):
        initialized = [name for name in locals_ if name in loop.header_names]
        unknown = [name for name in locals_ if name not in loop.header_names]
        slots = seq(f"some (.int {current[name]})" if name in loop.header_names else current[name]
                    for name in locals_)
        binders = []
        for names, type_ in ((initialized, "Int"), (unknown, "Option Value")):
            if names:
                binders.append(f"({' '.join(current[name] for name in names)} : {type_})")
        rank = expression(loop.decreases, current, old) if loop.decreases else None
        facts = [expression(loop.invariant, current, old)]
        if rank is not None:
            facts.append(f"0 ≤ {rank}")
        # Entry snapshots are local to this loop invocation, not old(parameter).
        # Equalities become proof obligations on every loop backedge.
        facts.extend(f"current.locals[{i}]? = entry.locals[{i}]?"
                     for i, name in enumerate(locals_) if name not in loop.modified_names)
        text += f"""
def map{index} : Frontend.Mapping := sourceMaps.loops[{index}]!

def invariant{index} (old : {ghost}) (entry current : Frame) : Prop :=
  ∃ {' '.join(binders)},
    current = {{ pc := map{index}.header, locals := {slots} }} ∧
    {' ∧ '.join(facts)}
"""
        if rank is not None:
            if annotation_reads(loop.decreases).intersection(locals_):
                body = f"match current.locals with\n  | {slots} => ({rank}).toNat\n  | _ => 0"
            else:
                # A constant/ghost measure needs no case split on local tags.
                body = f"({rank}).toNat"
            text += f"""
def rank{index} (old : {ghost}) (current : Frame) : Nat :=
  {body}
"""
            rules.append(f"rank{index}")
        text += f"""
def loop{index} : VC.ScopedLoop ({ghost}) where
  header := map{index}.header
  exits := map{index}.exitEdges.map Frontend.Edge.targetPC
  invariant old _ := invariant{index} old
"""
        if rank is not None:
            text += f"  ranking := some (fun old _ => rank{index} old)\n"
        rules.extend([f"map{index}", f"invariant{index}", f"loop{index}"])
    text += f"""
def specification : VC.ScopedSpecification ({ghost}) where
  contract := contract
  mode := .{'totalCorrectness' if function.mode == 'total' else 'partialCorrectness'}
  loops := {seq(f'loop{i}' for i in range(len(function.loops)))}

veripy_generate generated from admitted for specification unfolding [{', '.join(rules)}]
"""
    return text
